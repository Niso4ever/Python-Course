def demo_2_multi_agent():
    print("\n" + "="*60)
    print("DEMO 2: Multi-Agent Pipeline (Research → Write)")
    print("="*60)

    goal = "Write a brief report on AI trends in the healthcare sector"
    print(f"Goal: {goal}")

    if DEMO_MODE:
        # Step 1: Researcher gathers info
        print("\n[Orchestrator] Handing off to Researcher...")
        research_result = simulate_agent_run(
            agent_name="Researcher",
            task=f"Research: {goal}",
            tools_used=["search_knowledge"],
        )

        # Step 2: Writer produces final content
        print("\n[Orchestrator] Handing off to Writer...")
        write_result = simulate_agent_run(
            agent_name="Writer",
            task=f"Write article from research:\n{research_result.final_output}",
            tools_used=["format_report"],
        )
        result = write_result
    else:
        researcher = Agent(
            name="Researcher",
            instructions="Research topics using the search tool. Be thorough.",
            tools=[search_knowledge],
        )
        writer = Agent(
            name="Writer",
            instructions="Write clear, engaging reports from research. Use format_report for final output.",
            tools=[format_report],
        )
        orchestrator = Agent(
            name="Orchestrator",
            instructions="""Manage the research-to-report pipeline:
            1. Hand off to Researcher to gather sector information.
            2. Hand off to Writer to produce the final report.
            Return the completed report.""",
            handoffs=[researcher, writer],
        )
        result = Runner.run_sync(orchestrator, goal)

    print(f"\nFINAL REPORT:")
    print(result.final_output)
    print(f"\nCompleted by: {result.last_agent.name}")


