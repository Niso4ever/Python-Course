class DemoRunResult:
    """Simulates the RunResult object returned by Runner.run_sync."""
    def __init__(self, output: str, agent_name: str = "Agent"):
        self.final_output = output
        self.last_agent = type("Agent", (), {"name": agent_name})()
        self.messages = [
            {"role": "user", "content": "demo input"},
            {"role": "assistant", "content": output},
        ]
        self.new_messages = self.messages


def demo_search_knowledge(query: str) -> str:
    """Demo implementation of the search tool."""
    query_lower = query.lower()
    for key, value in DEMO_KNOWLEDGE.items():
        if key in query_lower or any(w in query_lower for w in key.split()):
            return value
    return f"No information found for: '{query}'"


def demo_format_report(title: str, content: str) -> str:
    """Demo implementation of the format tool."""
    return f"# {title}\n\n{content}\n\n---\n*Report generated by AI analyst*"


def demo_calculate_growth(current: float, previous: float) -> str:
    """Demo implementation of the calculator tool."""
    growth = ((current - previous) / previous) * 100
    direction = "growth" if growth >= 0 else "decline"
    return f"{abs(growth):.1f}% {direction} vs prior period"


def simulate_agent_run(agent_name: str, task: str, tools_used: list = None) -> DemoRunResult:
    """
    Simulates what Runner.run_sync would do:
    1. THINK: LLM reads task + tools
    2. ACT: calls tools if needed
    3. OBSERVE: processes results
    4. Loops until done
    5. Returns final answer
    """
    print(f"\n  [Demo] Agent '{agent_name}' received: {task[:60]}...")

    # Simulate tool usage based on task content
    tool_results = []
    if tools_used and "search" in str(tools_used):
        for keyword in ["energy", "healthcare", "fintech", "rag", "agentic"]:
            if keyword in task.lower():
                result = demo_search_knowledge(keyword)
                tool_results.append(result)
                print(f"  [Demo] Tool called: search_knowledge('{keyword}')")
                print(f"  [Demo] Tool result: {result[:60]}...")
                break

    # Simulate final answer
    if tool_results:
        answer = (
            f"Based on my research, here is the analysis:\n\n"
            f"{tool_results[0]}\n\n"
            f"Key takeaway: This sector presents significant opportunities "
            f"for organizations investing in AI-native workflows in 2026."
        )
    else:
        answer = (
            f"Analysis complete for: {task[:50]}...\n\n"
            f"The agentic AI landscape is evolving rapidly. "
            f"Organizations adopting direct API patterns are seeing 3x faster "
            f"iteration cycles compared to framework-dependent approaches."
        )

    print(f"  [Demo] Agent '{agent_name}' done.")
    return DemoRunResult(answer, agent_name)


