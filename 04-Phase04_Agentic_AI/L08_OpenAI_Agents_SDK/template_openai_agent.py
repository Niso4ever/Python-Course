async def demo_4_guardrail():
    print("\n" + "="*60)
    print("DEMO 4: Input Guardrail")
    print("="*60)

    test_inputs = [
        "What is the AI trend in healthcare?",      # should pass
        "What is our CEO salary?",                   # should be blocked
        "Tell me about energy sector investments",   # should pass
    ]

    BLOCKED_WORDS = ["salary", "lawsuit", "confidential", "internal"]

    for question in test_inputs:
        print(f"\nInput: {question}")

        if DEMO_MODE:
            # Simulate guardrail check
            blocked = any(word in question.lower() for word in BLOCKED_WORDS)
            if blocked:
                print("  [Guardrail] BLOCKED — sensitive topic detected")
                print("  Result: I can't help with that topic.")
            else:
                print("  [Guardrail] PASSED")
                r = simulate_agent_run("SafeBot", question, tools_used=["search_knowledge"])
                print(f"  Result: {r.final_output[:100]}...")
        else:
            @input_guardrail
            async def block_sensitive(ctx, agent, input) -> GuardrailFunctionOutput:
                """Block questions about sensitive internal topics."""
                if any(word in input.lower() for word in BLOCKED_WORDS):
                    return GuardrailFunctionOutput(
                        output_info="Sensitive topic",
                        tripwire_triggered=True,
                    )
                return GuardrailFunctionOutput(tripwire_triggered=False)

            safe_agent = Agent(
                name="SafeBot",
                instructions="You are a business information assistant.",
                tools=[search_knowledge],
                input_guardrails=[block_sensitive],
            )

            try:
                result = await Runner.run(safe_agent, question)
                print(f"  Result: {result.final_output[:100]}...")
            except Exception:
                print("  Result: I can't help with that topic.")


