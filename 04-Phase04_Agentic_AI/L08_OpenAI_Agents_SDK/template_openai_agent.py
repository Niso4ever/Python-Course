async def demo_3_parallel():
    print("\n" + "="*60)
    print("DEMO 3: Parallel Sector Analysis (3 agents at once)")
    print("="*60)

    sectors = ["energy", "healthcare", "fintech"]
    tasks = [f"Give a 2-sentence 2026 outlook for the {s} sector" for s in sectors]

    print(f"Running {len(sectors)} sector analyses in parallel...")

    if DEMO_MODE:
        # Simulate parallel by running sequentially with parallel framing
        results = []
        for sector, task in zip(sectors, tasks):
            r = simulate_agent_run(
                agent_name="SectorAnalyst",
                task=task,
                tools_used=["search_knowledge"],
            )
            results.append(r)
    else:
        analyst = Agent(
            name="SectorAnalyst",
            instructions="Give concise 2-sentence sector outlooks using current market data.",
            tools=[search_knowledge],
        )
        all_results = await asyncio.gather(
            *[Runner.run(analyst, task) for task in tasks]
        )
        results = all_results

    print("\nRESULTS:")
    for sector, result in zip(sectors, results):
        print(f"\n{sector.upper()} SECTOR:")
        print(result.final_output)


