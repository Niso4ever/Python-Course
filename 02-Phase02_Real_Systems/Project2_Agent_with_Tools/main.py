def run_interactive():
    """Interactive mode: choose a research brief or enter your own."""
    print("\n" + "="*60)
    print("NEXUS AI RESEARCH ANALYST")
    print("Powered by Claude Opus 5.5 | Tool Use + ReAct")
    print("="*60)

    print("\nChoose a research brief or enter your own:\n")
    for i, (name, brief) in enumerate(SAMPLE_BRIEFS, 1):
        print(f"  {i}. {name}")
    print(f"  {len(SAMPLE_BRIEFS)+1}. Enter custom brief")
    print()

    try:
        choice = input("Choice (1-5): ").strip()
    except (EOFError, KeyboardInterrupt):
        print("\nExiting.")
        return

    if choice.isdigit() and 1 <= int(choice) <= len(SAMPLE_BRIEFS):
        topic_name, brief = SAMPLE_BRIEFS[int(choice) - 1]
        print(f"\nResearching: {topic_name}")
        print(f"Brief: {brief[:100]}...\n")
    else:
        try:
            topic_name = input("Report title: ").strip() or "Custom Research Report"
            brief = input("Research brief (be specific): ").strip()
        except (EOFError, KeyboardInterrupt):
            print("\nExiting.")
            return
        if not brief:
            print("No brief provided. Exiting.")
            return

    from agent import ResearchAgent
    agent  = ResearchAgent(verbose=VERBOSE)
    result = agent.research(brief)

    # Print final answer
    if result["answer"]:
        print("\n" + "="*60)
        print("FINAL REPORT:")
        print("="*60)
        print(result["answer"])

    # Print tool summary
    print("\n" + "-"*60)
    print(agent.get_tool_summary())
    print(f"Total tool calls: {result['tool_calls_made']}")


def run_with_topic(topic_arg: str):
    """Run with a specific topic from command line."""
    idx = sys.argv.index("--topic")
    topic = sys.argv[idx + 1] if idx + 1 < len(sys.argv) else None
    if not topic:
        print("Usage: python main.py --topic 'Your research topic'")
        return

    brief = (
        f"Research the following topic thoroughly: {topic}\n\n"
        "Include: current state, key statistics, market data, trends, "
        "and actionable insights. Use web_search for current data, "
        "calculator for any math, and write_report to save the final report."
    )

    print(f"\nResearching: {topic}")
    from agent import ResearchAgent
    agent  = ResearchAgent(verbose=VERBOSE)
    result = agent.research(brief)

    if result["answer"]:
        print("\n" + "="*60)
        print(result["answer"])


